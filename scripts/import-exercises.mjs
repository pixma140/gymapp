import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_REVISION = '6f3031b3b2b2934890b6f26376d7e22bfc308d6a';
const SOURCE_URL = `https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/${SOURCE_REVISION}/data/exercises.json`;
const OUTPUT = fileURLToPath(new URL('../shared/exercises.js', import.meta.url));

const targetGroups = {
    abductors: 'abductors',
    abs: 'abs',
    adductors: 'adductors',
    biceps: 'biceps',
    calves: 'calves',
    'cardiovascular system': 'cardio',
    delts: 'shoulders',
    forearms: 'forearms',
    glutes: 'glutes',
    hamstrings: 'hamstrings',
    lats: 'lats',
    'levator scapulae': 'traps',
    pectorals: 'chest',
    quads: 'quadriceps',
    'serratus anterior': 'chest',
    spine: 'lowerBack',
    traps: 'traps',
    triceps: 'triceps',
    'upper back': 'middleBack',
};

const additionalCardio = [
    ['walking-pad', 'Walking pad'],
    ['stairmaster', 'StairMaster'],
    ['jogging', 'Jogging'],
    ['inline-skating', 'Inline skating'],
];

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Exercise import failed: ${response.status} ${response.statusText}`);
const source = await response.json();
if (!Array.isArray(source)) throw new Error('Exercise import failed: expected an array');

const exercises = source.map(exercise => {
    const muscleGroup = targetGroups[exercise.target];
    if (!muscleGroup) throw new Error(`Exercise import failed: unmapped target ${exercise.target}`);
    return {
        id: `dataset:${exercise.id}`,
        name: exercise.name,
        equipment: exercise.equipment,
        muscleGroup,
    };
});

for (const [id, name] of additionalCardio) {
    exercises.push({ id: `cardio:${id}`, name, equipment: 'cardio', muscleGroup: 'cardio' });
}

exercises.sort((left, right) => left.name.localeCompare(right.name, 'en'));
const output = `// Generated by npm run exercises:import from exercises-dataset revision ${SOURCE_REVISION}.\n`
    + `export const EXERCISE_SOURCE = ${JSON.stringify({ repository: 'https://github.com/hasaneyldrm/exercises-dataset', revision: SOURCE_REVISION })};\n`
    + `export const EXERCISES = Object.freeze(${JSON.stringify(exercises, null, 4)});\n`
    + 'export const EXERCISE_IDS = new Set(EXERCISES.map(exercise => exercise.id));\n';

await writeFile(OUTPUT, output);
console.log(`Imported ${exercises.length} exercises from ${SOURCE_REVISION}.`);
